"""Alembic regression tests against real PostgreSQL + pgvector.

Skipped unless MIGRATION_TEST_DATABASE_URL points at a server whose role may
CREATE DATABASE and CREATE EXTENSION, e.g.
    MIGRATION_TEST_DATABASE_URL=postgresql+psycopg://postgres:pw@127.0.0.1:55433/postgres
Each test runs in its own throwaway database, which is dropped afterwards.
"""
from __future__ import annotations

import os
from pathlib import Path
from uuid import uuid4

import pytest
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

ADMIN_URL = os.environ.get("MIGRATION_TEST_DATABASE_URL")
pytestmark = pytest.mark.skipif(not ADMIN_URL, reason="MIGRATION_TEST_DATABASE_URL not set")

ROOT = Path(__file__).resolve().parent.parent
APP_TABLES = {
    "tenants", "chunks", "customers", "orders", "order_items", "refund_history", "operation_log",
}


@pytest.fixture()
def db_url(monkeypatch):
    from alembic.config import Config  # noqa: F401  (fail early if alembic is missing)

    import app.config

    name = f"mig_test_{uuid4().hex[:12]}"
    admin = create_engine(ADMIN_URL, isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{name}"'))
    url = make_url(ADMIN_URL).set(database=name).render_as_string(hide_password=False)
    # alembic/env.py reads app.config.setting.database_url.
    monkeypatch.setattr(app.config.setting, "database_url", url)
    try:
        yield url
    finally:
        with admin.connect() as conn:
            conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin.dispose()


def _cfg():
    from alembic.config import Config

    # No ini file: keeps env.py from calling logging.fileConfig() inside the test run.
    cfg = Config()
    cfg.set_main_option("script_location", str(ROOT / "alembic"))
    return cfg


def _head() -> str:
    from alembic.script import ScriptDirectory

    heads = ScriptDirectory.from_config(_cfg()).get_heads()
    assert len(heads) == 1, heads
    return heads[0]


def _version(url: str) -> str | None:
    engine = create_engine(url)
    try:
        with engine.connect() as conn:
            if not inspect(conn).has_table("alembic_version"):
                return None
            return conn.scalar(text("SELECT version_num FROM alembic_version"))
    finally:
        engine.dispose()


def _tables(url: str) -> set[str]:
    engine = create_engine(url)
    try:
        with engine.connect() as conn:
            return set(inspect(conn).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()


def test_single_linear_head():
    _head()


def test_upgrade_head_on_empty_database_and_check_is_clean(db_url):
    from alembic import command

    command.upgrade(_cfg(), "head")
    assert _version(db_url) == _head()
    assert _tables(db_url) == APP_TABLES
    command.check(_cfg())  # raises AutoGenerateDiffsDetected on any ORM drift


def test_downgrade_base_then_upgrade_head(db_url):
    from alembic import command

    command.upgrade(_cfg(), "head")
    command.downgrade(_cfg(), "base")
    assert _version(db_url) is None
    assert _tables(db_url) == set()
    command.upgrade(_cfg(), "head")
    assert _version(db_url) == _head()
    command.check(_cfg())


def test_existing_tenant_and_chunk_data_survive_upgrade(db_url):
    from alembic import command

    command.upgrade(_cfg(), "a7f2e3c41b90")
    tenant_id = uuid4()
    engine = create_engine(db_url)
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO tenants (id, name, api_key_hash) VALUES (:i, 'kept', 'h')"),
                     {"i": tenant_id})
        conn.execute(text(
            "INSERT INTO chunks (tenant_id, source_document_id, chunk_index, content, embedding) "
            "VALUES (:i, 'doc', 0, 'refund policy text', :e)"
        ), {"i": tenant_id, "e": "[" + ",".join(["0.1"] * 384) + "]"})

    command.upgrade(_cfg(), "head")

    with engine.connect() as conn:
        assert conn.execute(text("SELECT id, name FROM tenants")).all() == [(tenant_id, "kept")]
        row = conn.execute(text(
            "SELECT tenant_id, content, content_tsv IS NOT NULL FROM chunks"
        )).one()
        assert tuple(row) == (tenant_id, "refund policy text", True)
    engine.dispose()
    command.check(_cfg())


def test_unique_tenant_name_migration_waits_for_dedupe(db_url):
    from alembic import command

    from scripts.dedupe_tenant_names import apply_renames, load_tenants, plan_renames

    command.upgrade(_cfg(), "63b935d2d7a7")
    keeper, other = uuid4(), uuid4()
    engine = create_engine(db_url)
    with engine.begin() as conn:
        for tid in (keeper, other):
            conn.execute(text("INSERT INTO tenants (id, name, api_key_hash) VALUES (:i, 'Test Tenant', 'h')"),
                         {"i": tid})
        conn.execute(text(
            "INSERT INTO chunks (tenant_id, source_document_id, chunk_index, content, embedding) "
            "VALUES (:i, 'doc', 0, 'x', :e)"
        ), {"i": keeper, "e": "[" + ",".join(["0"] * 384) + "]"})

    with pytest.raises(RuntimeError, match="duplicates exist: 'Test Tenant' x2"):
        command.upgrade(_cfg(), "head")
    assert _version(db_url) == "63b935d2d7a7"

    with engine.begin() as conn:
        apply_renames(conn, plan_renames(load_tenants(conn)))
    command.upgrade(_cfg(), "head")
    assert _version(db_url) == _head()

    with engine.connect() as conn:
        names = dict(conn.execute(text("SELECT id, name FROM tenants")).all())
        assert names == {keeper: "Test Tenant", other: f"Test Tenant [{other.hex[:8]}]"}
        assert conn.scalar(text("SELECT tenant_id FROM chunks")) == keeper
        with pytest.raises(Exception, match="tenants_name_key"):
            conn.execute(text("INSERT INTO tenants (id, name, api_key_hash) VALUES (:i, 'Test Tenant', 'h')"),
                         {"i": uuid4()})
    engine.dispose()
